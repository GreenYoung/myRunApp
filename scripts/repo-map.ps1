param(
    [string]$RepoRoot = (Split-Path $PSScriptRoot -Parent),
    [string]$Output = "docs/REPO_MAP.md"
)

$ErrorActionPreference = 'Stop'

$sourceRoots = @('app/src/main', 'app/src/test')
$files = @(
    foreach ($root in $sourceRoots) {
        $dir = Join-Path $RepoRoot $root
        if (Test-Path $dir) {
            Get-ChildItem $dir -Recurse -Filter *.kt
        }
    }
) | Sort-Object FullName

function Get-TopLevelDeclarations {
    param([string[]]$Lines)

    $found = New-Object System.Collections.Generic.List[object]
    for ($i = 0; $i -lt $Lines.Count; $i++) {
        $line = $Lines[$i]
        if ([string]::IsNullOrWhiteSpace($line)) { continue }
        if ($line.StartsWith(' ') -or $line.StartsWith("`t")) { continue }
        if ($line.StartsWith('//')) { continue }

        $kind = $null
        $name = $null

        if ($line -match '^(?:(?:internal|private|public)\s+)*enum\s+class\s+([A-Za-z_]\w*)') {
            $kind = 'enum'
            $name = $Matches[1]
        } elseif ($line -match '^(?:(?:@\w+(?:\([^)]*\))?\s*)?(?:internal|private|public|protected|data|sealed|abstract|open|enum|value|annotation|inline|suspend|operator|infix|tailrec|override|expect|actual)\s+)*(class|interface|object|typealias)\s+([A-Za-z_]\w*)') {
            $kind = $Matches[1]
            $name = $Matches[2]
        } elseif ($line -match '^(?:(?:@\w+(?:\([^)]*\))?\s*)?(?:internal|private|public|inline|suspend|operator|infix|tailrec|override|expect|actual)\s+)*fun\s+(?:<[^>]*>\s*)?(?:[A-Za-z_][\w.<>?, ]*\.)?([A-Za-z_]\w*)\s*\(') {
            $kind = 'fun'
            $name = $Matches[1]
        } elseif ($line -match '^const\s+val\s+([A-Za-z_]\w*)') {
            $kind = 'const'
            $name = $Matches[1]
        }

        if ($name) {
            $found.Add([pscustomobject]@{ Line = $i + 1; Kind = $kind; Name = $name })
        }
    }
    return $found
}

function Get-LeadingDoc {
    param([string[]]$Lines, [int]$MaxScan = 12)

    for ($i = 0; $i -lt [Math]::Min($MaxScan, $Lines.Count); $i++) {
        $line = $Lines[$i].Trim()
        if ($line -eq '') { continue }
        if ($line.StartsWith('*') -or $line.StartsWith('/*') -or $line.StartsWith('*/')) { return $line.TrimStart('/', '*', ' ') }
        return $null
    }
    return $null
}

function Format-Declaration {
    param($Declaration)

    $prefix = switch ($Declaration.Kind) {
        'class' { 'class' }
        'interface' { 'interface' }
        'object' { 'object' }
        'fun' { 'fun' }
        'const' { 'const' }
        default { $Declaration.Kind }
    }
    return "$prefix $($Declaration.Name)(L$($Declaration.Line))"
}

$totalLines = 0
$builder = New-Object System.Text.StringBuilder

[void]$builder.AppendLine('<!-- AUTO-GENERATED:START -->')
[void]$builder.AppendLine('')
[void]$builder.AppendLine("_Auto-generated by ``scripts/repo-map.ps1``. Do not edit this block by hand; rerun the script after code changes._")
[void]$builder.AppendLine('')

$groups = $files | Group-Object {
    $relative = $_.FullName.Substring($RepoRoot.Length).TrimStart('\', '/')
    $directory = Split-Path $relative -Parent
    $directory = $directory -replace '\\', '/'
    $directory = $directory -replace '^app/src/main/java/com/example/myrunapp/?', ''
    $directory = $directory -replace '^app/src/main/java/?', ''
    $directory = $directory -replace '^app/src/test/java/com/example/myrunapp/?', 'test/'
    if ([string]::IsNullOrWhiteSpace($directory)) { 'root' } else { $directory }
}

$fileCount = 0
foreach ($group in ($groups | Sort-Object Name)) {
    [void]$builder.AppendLine("### $($group.Name)")
    [void]$builder.AppendLine('')

    foreach ($file in ($group.Group | Sort-Object Name)) {
        $fileCount++
        $lines = Get-Content $file.FullName
        $totalLines += $lines.Count
        $declarations = @(Get-TopLevelDeclarations -Lines $lines)
        $doc = Get-LeadingDoc -Lines $lines

        $summary = if ($doc) { " - $doc" } else { '' }
        [void]$builder.AppendLine("- ``$($file.Name)`` ($($lines.Count) lines)$summary")

        if ($declarations.Count -gt 0) {
            $formatted = ($declarations | ForEach-Object { Format-Declaration $_ }) -join '; '
            [void]$builder.AppendLine("  - $formatted")
        }
    }
    [void]$builder.AppendLine('')
}

[void]$builder.AppendLine("_$fileCount Kotlin files, $totalLines lines._")
[void]$builder.AppendLine('')
[void]$builder.AppendLine('<!-- AUTO-GENERATED:END -->')

$generated = $builder.ToString()
$outPath = Join-Path $RepoRoot $Output
$outDir = Split-Path $outPath -Parent
if (-not (Test-Path $outDir)) {
    New-Item -ItemType Directory -Path $outDir -Force | Out-Null
}

$writeAll = $true
if (Test-Path $outPath) {
    # Read explicitly as UTF-8: PowerShell 5.1 Get-Content defaults to ANSI and would mangle non-ASCII text.
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    $existing = [System.IO.File]::ReadAllText($outPath, $utf8NoBom)
    $startMarker = '<!-- AUTO-GENERATED:START -->'
    $endMarker = '<!-- AUTO-GENERATED:END -->'
    $startIndex = $existing.IndexOf($startMarker)
    $endIndex = $existing.IndexOf($endMarker)

    if ($startIndex -ge 0 -and $endIndex -gt $startIndex) {
        $head = $existing.Substring(0, $startIndex)
        # Trim the newlines that follow the END marker so repeated runs stay byte-identical.
        $tail = $existing.Substring($endIndex + $endMarker.Length).TrimStart([char]13, [char]10)
        $result = $head + $generated + $tail
        if (-not $result.EndsWith("`n")) { $result += "`n" }
        [System.IO.File]::WriteAllText($outPath, $result, $utf8NoBom)
        $writeAll = $false
    }
}

if ($writeAll) {
    $template = @"
# Repo Map

> Source map for humans and AI: locate file + symbol here, then grep and read a small window.
> Regenerate the auto block with ``pwsh -File scripts/repo-map.ps1`` after code changes.

$generated
"@
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($outPath, $template, $utf8NoBom)
}

Write-Host "Repo map written to $outPath ($fileCount files, $totalLines lines)"
